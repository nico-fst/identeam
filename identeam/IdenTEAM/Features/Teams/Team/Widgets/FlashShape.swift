        guard rect.width > 0, rect.height > 0 else { return Path() }

        // Preserve the SVG's square 512 x 512 viewBox and its original padding
        let scale = min(rect.width, rect.height) / 512
        var transform = CGAffineTransform(
            a: scale, b: 0, c: 0, d: scale,
            tx: rect.midX - 256 * scale, ty: rect.midY - 256 * scale
        )
        guard let contour = Self.contour.copy(using: &transform) else { return Path() }
        guard insetAmount != 0 else { return Path(contour) }
        let bounds = contour.boundingBoxOfPath
        guard insetAmount < min(bounds.width, bounds.height) / 2 else { return Path() }

        // Offset the contour in points, including its concave corners
        let border = contour.copy(
            strokingWithWidth: abs(insetAmount) * 2,
            lineCap: .round, lineJoin: .round, miterLimit: 10
        )
        return Path(
            insetAmount > 0 ? contour.subtracting(border) : contour.union(border)
        )
    }

    func inset(by amount: CGFloat) -> FlashShape {
        var shape = self
        shape.insetAmount += amount
        return shape
    }

